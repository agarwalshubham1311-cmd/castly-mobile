const { chromium } = require('playwright');
(async () => {
 const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror', e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL || 'http://127.0.0.1:8082');
 await page.getByRole('button',{name:"View Aria Kapoor's profile"}).waitFor();
 await page.getByRole('button',{name:'Actors',exact:true}).click();
 if(await page.getByRole('button',{name:/View .*profile/}).count()!==1)throw Error('Category filter');
 await page.getByRole('button',{name:"View Aria Kapoor's profile"}).click();
 await page.getByText('A little about me').waitFor();
 await page.getByRole('button',{name:'♡ Save',exact:true}).click();
 await page.getByRole('button',{name:'← Back to discovery'}).click();
 await page.getByRole('tab',{name:'♡ Saved'}).click();
 await page.getByRole('button',{name:"View Aria Kapoor's profile"}).waitFor();
 await page.getByRole('tab',{name:'✦ Discover'}).click();
 await page.getByRole('button',{name:'All talent',exact:true}).click();
 await page.getByRole('button',{name:'Filters ☷'}).click();
 await page.getByRole('button',{name:'Delhi',exact:true}).click();
 await page.getByRole('button',{name:'Show 1 results'}).click();
 await page.getByRole('button',{name:"View Rehan Mehta's profile"}).waitFor();
 await page.getByRole('button',{name:'Filters (1)'}).click();
 await page.getByRole('button',{name:'Reset filters'}).click();
 await page.getByRole('button',{name:'Show 4 results'}).click();
 await page.getByRole('textbox').fill('no matching talent');
 await page.getByText('No talent found',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Reset search & filters'}).click();
 await page.getByRole('button',{name:'Close',exact:true}).waitFor({state:'hidden'});
 await page.waitForTimeout(400);
 await page.screenshot({path:'/tmp/castly-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.setViewportSize({width:1024,height:900});
 if(await page.getByRole('button',{name:/View .*profile/}).count()!==4)throw Error('Catalog reset');
 await page.screenshot({path:'/tmp/castly-tablet.png',fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: category, profile, save, tabs, filters, empty/reset, mobile/tablet layout; no browser errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
